const assert = require('assert');
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const root = path.join(__dirname, '..');
const route = fs.readFileSync(path.join(root, 'app/studio/page.tsx'), 'utf8');
const component = fs.readFileSync(path.join(root, 'components/studio/StudioIndex.tsx'), 'utf8');
const group = fs.readFileSync(path.join(root, 'components/GroupedWorkspace.tsx'), 'utf8');
const library = fs.readFileSync(path.join(root, 'app/document-library/page.tsx'), 'utf8');
const ast = ts.createSourceFile('page.tsx', route, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
assert.equal(ast.parseDiagnostics.length, 0, 'Route must parse');
const exported = ast.statements.filter(st => ts.isFunctionDeclaration(st) && st.modifiers && st.modifiers.some(mod => mod.kind === ts.SyntaxKind.DefaultKeyword));
assert.equal(exported.length, 1, 'Route must have one default page function');
assert.equal(exported[0].parameters.length, 0, 'Next.js route must not accept embedded/custom props');
assert(route.includes('../../components/studio/StudioIndex'), 'Route must import shared StudioIndex');
assert(component.includes('embedded=false') && component.includes('studio-hub-embedded'), 'Shared component must preserve embedded mode');
assert(group.includes('from "./studio/StudioIndex"') && group.includes('<StudioIndex embedded/>'), 'Tools must use shared embedded StudioIndex');
assert(library.includes('from "../../components/studio/StudioIndex"'), 'Document Library must use reusable StudioIndex');
console.log('PASS Studio route/default export Next.js compatibility and Tools/Document Library embed preservation');
